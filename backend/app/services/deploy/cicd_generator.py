"""
CI/CD Workflow Pipeline Generator
"""

class CicdGeneratorService:
    def generate_github_actions_yaml(self, project_name: str, language: str = "node-express") -> str:
        return f"""# Generated by StaticFlow
name: CI/CD Pipeline - {project_name}

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Setup Runtime
        uses: actions/setup-node@v4
        with:
          node-version: 20
      - run: npm ci
      - run: npm test

  security-scan:
    needs: test
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Run OWASP Audit
        run: npx @staticflow/cli scan --strict
"""


cicd_generator = CicdGeneratorService()
