"""
Deterministic OpenAPI Specification Builder
"""

import json


class OpenapiGeneratorService:
    def build_spec(self, title: str, endpoints: list[dict], version: str = "1.0.0") -> dict:
        paths = {}
        for ep in endpoints:
            p = ep.get("path", "/api/v1/items")
            m = ep.get("method", "GET").lower()
            paths.setdefault(p, {})[m] = {
                "summary": ep.get("summary", "Endpoint description"),
                "responses": {
                    "200": {"description": "Successful operation"},
                    "400": {"description": "Bad request"},
                    "401": {"description": "Unauthorized"},
                },
            }

        return {
            "openapi": "3.1.0",
            "info": {"title": title, "version": version, "description": "Generated by StaticFlow"},
            "paths": paths,
        }


openapi_generator = OpenapiGeneratorService()
