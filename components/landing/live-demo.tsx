"use client";

import { useState } from "react";
import { Play, Loader2, CheckCircle2, Copy, Terminal } from "lucide-react";

const demoSteps = [
  { label: "Parsing intent...", duration: 800 },
  { label: "Designing database schema...", duration: 1000 },
  { label: "Generating 24 endpoints...", duration: 1200 },
  { label: "Adding JWT authentication...", duration: 800 },
  { label: "Writing input validation...", duration: 600 },
  { label: "Running security scan...", duration: 1000 },
  { label: "Generating documentation...", duration: 700 },
  { label: "Preparing deployment...", duration: 500 },
];

const generatedCode = `// ✅ Auto-generated by StaticFlow
import express from 'express';
import { PrismaClient } from '@prisma/client';
import { authenticate, authorize } from './middleware';
import { validate } from './validators';

const app = express();
const prisma = new PrismaClient();

app.use(express.json());

// POST /api/auth/register
app.post('/api/auth/register',
  validate(registerSchema),
  async (req, res) => {
    const { email, password, name } = req.body;
    const hash = await bcrypt.hash(password, 12);
    const user = await prisma.user.create({
      data: { email, password: hash, name }
    });
    const token = generateJWT(user);
    res.status(201).json({ user, token });
  }
);

// GET /api/posts
app.get('/api/posts',
  authenticate,
  async (req, res) => {
    const posts = await prisma.post.findMany({
      include: { author: true, comments: true },
      orderBy: { createdAt: 'desc' },
      take: 20
    });
    res.json({ data: posts });
  }
);

app.listen(3000, () => {
  console.log('🚀 API running on port 3000');
});`;

export function LiveDemo() {
  const [isRunning, setIsRunning] = useState(false);
  const [currentStep, setCurrentStep] = useState(-1);
  const [isComplete, setIsComplete] = useState(false);
  const [copied, setCopied] = useState(false);

  const runDemo = async () => {
    setIsRunning(true);
    setCurrentStep(0);
    setIsComplete(false);

    for (let i = 0; i < demoSteps.length; i++) {
      setCurrentStep(i);
      await new Promise((r) => setTimeout(r, demoSteps[i].duration));
    }

    setIsComplete(true);
    setIsRunning(false);
  };

  const copyCode = () => {
    navigator.clipboard.writeText(generatedCode);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="glass-card overflow-hidden">
      {/* Header */}
      <div className="flex items-center justify-between border-b border-cyber-white/5 px-6 py-3">
        <div className="flex items-center gap-2">
          <Terminal className="h-4 w-4 text-cyber-cyan" />
          <span className="text-sm font-mono text-cyber-white/60">
            staticflow-demo
          </span>
        </div>
        <button
          onClick={runDemo}
          disabled={isRunning}
          className="flex items-center gap-2 rounded-lg bg-cyber-cyan/10 border border-cyber-cyan/20
                     px-4 py-1.5 text-xs font-bold text-cyber-cyan
                     hover:bg-cyber-cyan/20 transition-all disabled:opacity-50"
        >
          {isRunning ? (
            <Loader2 className="h-3 w-3 animate-spin" />
          ) : (
            <Play className="h-3 w-3" />
          )}
          {isRunning ? "Building..." : "Run Demo"}
        </button>
      </div>

      <div className="grid lg:grid-cols-2">
        {/* Left: Build Log */}
        <div className="border-b border-cyber-white/5 p-6 lg:border-b-0 lg:border-r">
          <h3 className="mb-4 text-xs font-bold uppercase tracking-wider text-cyber-white/30">
            Build Log
          </h3>

          {/* Prompt */}
          <div className="mb-4 rounded-lg border border-cyber-cyan/10 bg-cyber-cyan/5 p-3">
            <p className="text-xs text-cyber-cyan/60 mb-1">Prompt:</p>
            <p className="text-sm text-cyber-white/80 font-mono">
              &quot;Build a blog API with user auth, posts, comments, and likes&quot;
            </p>
          </div>

          {/* Steps */}
          <div className="space-y-2">
            {demoSteps.map((step, i) => {
              const isActive = i === currentStep && isRunning;
              const isDone = i < currentStep || isComplete;

              return (
                <div
                  key={i}
                  className={`flex items-center gap-2 rounded px-2 py-1.5 text-sm transition-all ${
                    isActive
                      ? "bg-cyber-cyan/5 text-cyber-cyan"
                      : isDone
                        ? "text-cyber-green/70"
                        : "text-cyber-white/20"
                  }`}
                >
                  {isDone ? (
                    <CheckCircle2 className="h-3.5 w-3.5 shrink-0" />
                  ) : isActive ? (
                    <Loader2 className="h-3.5 w-3.5 shrink-0 animate-spin" />
                  ) : (
                    <div className="h-3.5 w-3.5 shrink-0 rounded-full border border-cyber-white/10" />
                  )}
                  <span className="font-mono text-xs">{step.label}</span>
                </div>
              );
            })}
          </div>

          {isComplete && (
            <div className="mt-4 rounded-lg border border-cyber-green/20 bg-cyber-green/5 p-3">
              <p className="text-xs font-bold text-cyber-green">
                ✅ Build complete — 24 endpoints generated in 6.2s
              </p>
            </div>
          )}
        </div>

        {/* Right: Generated Code */}
        <div className="relative p-6">
          <div className="flex items-center justify-between mb-4">
            <h3 className="text-xs font-bold uppercase tracking-wider text-cyber-white/30">
              Generated Code
            </h3>
            <button
              onClick={copyCode}
              className="flex items-center gap-1 text-xs text-cyber-white/30 hover:text-cyber-cyan transition-colors"
            >
              {copied ? (
                <>
                  <CheckCircle2 className="h-3 w-3" /> Copied
                </>
              ) : (
                <>
                  <Copy className="h-3 w-3" /> Copy
                </>
              )}
            </button>
          </div>
          <pre className="code-block text-xs leading-relaxed overflow-auto max-h-[400px]">
            <code className="text-cyber-white/60">
              {isComplete || isRunning
                ? generatedCode
                : '// Click "Run Demo" to generate code...'}
            </code>
          </pre>
        </div>
      </div>
    </div>
  );
}
